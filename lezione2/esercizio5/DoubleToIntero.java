package lezione2.esercizio5;

public class DoubleToIntero {
	
	public static void doppioAdIntero(double numeroDoppio) {
		int numeroIntero = (int) numeroDoppio; // CAST da doppio ad intero
		System.out.println("numero doppio " + numeroDoppio);
		System.out.println("numero intero " + numeroIntero);
		
	}
}
