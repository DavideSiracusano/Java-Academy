package lezione4.esercizio8;

public class IsCompreso {
	
	public static void main(String [] args) {
		
		int numero = 10;
		
		// vedere se il numero è compreso tra 0 e 10 con operatore logico
		if(numero >= 0 && numero <= 10) {
			System.out.println("il numero " + numero + " è " + " compreso tra 1 e 10");
		}
		else {
			System.out.println("il numero " + numero + " non è " + " compreso tra 1 e 10");

		}
		
	}
}

